// The skill scaffold: SKILL.md from the Draft, a placeholder for every file a step names, and a `source/README.md`
// saying what is left to do. Placeholders are derived from the Draft on every export and never stored in it, so a
// path edited in the panel moves its placeholder with it. A file carried with the draft (an import, S4) is emitted
// as it is, in place of a placeholder at its path and also when no step names it.

import { packSkill, utf8, type ZipFile } from "../zip";
import type { Draft, IOItem, Step } from "./draft";
import { lint, PLACEHOLDER_MARKER, type Issue } from "./lint";
import { draftToSkillMd } from "./serialize";

export const README_PATH = "source/README.md";
/** Where the Studio's notes go when the skill already has a source/README.md of its own (an import). */
export const NOTES_PATH = "source/STUDIO.md";
/** The line that marks the notes as the Studio's own, so a re-import drops them. */
export const STUDIO_NOTE = "Generated by the aip console's Studio as a skill scaffold.";

export interface Placeholder {
  path: string;
  text: string;
  mode: number;
  /** The step that names the file (the first one, when several do). */
  stepId: string;
  what: "script" | "template" | "asset" | "reference";
}

/** A relative path under `prefix/` with no empty, `.` or `..` part: the only kind a placeholder is made at. A path
 *  the schema rejects gets no file; the linter already reports it. */
function safe(path: string | undefined, prefix: string): path is string {
  if (!path || !path.startsWith(`${prefix}/`)) return false;
  return path.split("/").every((p) => p !== "" && p !== "." && p !== "..");
}

const stem = (path: string) => path.slice(path.lastIndexOf("/") + 1).replace(/\.[^.]*$/, "");
const ext = (path: string) => (/\.([^./]+)$/.exec(path)?.[1] ?? "").toLowerCase();
const IDENTIFIER = /^[A-Za-z_][A-Za-z0-9_]*$/;

/** Every placeholder the Draft calls for, keyed by path, in step order. An execution step launched with anything
 *  but Python gets no stub (the linter marks it unfinished). */
export function placeholders(draft: Draft): Map<string, Placeholder> {
  const out = new Map<string, Placeholder>();
  const put = (p: Placeholder) => { if (!out.has(p.path)) out.set(p.path, p); };
  const nextOf = (s: Step) => draft.steps.find((x) => x.id === s.next);

  for (const s of draft.steps) {
    if (s.kind === "execution" && safe(s.script, "scripts") && (s.command === undefined || s.command[0] === "python")) {
      put({ path: s.script, text: pythonStub(draft, s, nextOf(s)), mode: 0o755, stepId: s.id, what: "script" });
    }
    if (s.kind === "client_task" && safe(s.template, "assets")) {
      put({ path: s.template, text: templateStub(s), mode: 0o644, stepId: s.id, what: "template" });
    }
    if (s.kind === "client_task") {
      for (const r of s.references ?? []) {
        if (safe(r.path, "references")) put({ path: r.path, text: referenceStub(r.path, r.description), mode: 0o644, stepId: s.id, what: "reference" });
      }
    }
    if (s.kind === "execution" || s.kind === "client_task") {
      for (const a of s.assets ?? []) if (safe(a, "assets")) put({ path: a, text: assetStub(a), mode: 0o644, stepId: s.id, what: "asset" });
    }
  }
  return out;
}

/** The text of each file the skill will hold apart from SKILL.md, for the linter's `placeholder_file` check. */
export function fileTexts(draft: Draft, carried: ZipFile[] = []): Record<string, string> {
  const texts: Record<string, string> = {};
  for (const [path, p] of placeholders(draft)) texts[path] = p.text;
  const decoder = new TextDecoder();
  for (const f of carried) texts[f.path] = decoder.decode(f.bytes);
  return texts;
}

export interface Scaffold {
  /** The zip's top folder and the file name's stem. */
  name: string;
  files: ZipFile[];
  issues: Issue[];
  /** The placeholder files in the zip (a carried file at the same path replaces its placeholder). */
  placeholders: Placeholder[];
}

/** The scaffold's files: SKILL.md, the carried files, a placeholder for each referenced file nothing carries, and
 *  the README. The linter runs on the Draft and these files first, and the README reports what it found. */
export function buildScaffold(draft: Draft, carried: ZipFile[] = []): Scaffold {
  const name = draft.name || "untitled-skill";
  const issues = lint(draft, { files: fileTexts(draft, carried) });
  const have = new Set(carried.map((f) => f.path));
  const made = [...placeholders(draft).values()].filter((p) => !have.has(p.path));

  const files: ZipFile[] = [{ path: "SKILL.md", bytes: utf8(draftToSkillMd(draft)), mode: 0o644 }];
  for (const f of carried) if (f.path !== "SKILL.md") files.push(f);
  for (const p of made) files.push({ path: p.path, bytes: utf8(p.text), mode: p.mode });
  // An imported skill's own source/README.md is kept; the notes go beside it.
  const notes = have.has(README_PATH) ? NOTES_PATH : README_PATH;
  if (!have.has(notes)) files.push({ path: notes, bytes: utf8(readme(draft, issues, made)), mode: 0o644 });
  files.sort((a, b) => (a.path < b.path ? -1 : 1));
  return { name, files, issues, placeholders: made };
}

/** The scaffold as a zip in the Agent Skills layout, one `<name>/` folder. */
export function packScaffold(s: Scaffold): Uint8Array {
  return packSkill(s.name, s.files);
}

// ------------------------------------------------------------------------------------------------ the README

function readme(draft: Draft, issues: Issue[], made: Placeholder[]): string {
  const name = draft.name || "untitled-skill";
  const label = (id: string | undefined) => {
    const s = draft.steps.find((x) => x.id === id);
    return s ? `step \`${s.name || s.id}\`: ` : "";
  };
  const errors = issues.filter((i) => i.tier === "error");
  const unfinished = issues.filter((i) => i.tier === "unfinished" && i.code !== "placeholder_file");
  const lines = [`# ${name}`, "", STUDIO_NOTE, ""];
  if (errors.length) {
    lines.push(`DRAFT: ${errors.length} error${errors.length === 1 ? "" : "s"} remain${errors.length === 1 ? "s" : ""}. \`aip-spec validate\` rejects this skill until they are fixed:`, "");
    for (const i of errors) lines.push(`- ${label(i.stepId)}${i.message} (\`${i.code}\`)`);
    lines.push("");
  }
  lines.push("## Unfinished placeholders", "");
  if (made.length === 0) lines.push("None.");
  for (const p of made) lines.push(`- \`${p.path}\` (${p.what} of ${label(p.stepId).replace(/: $/, "")})`);
  lines.push("", `Each placeholder holds the marker \`${PLACEHOLDER_MARKER}\`; replace the file's content to finish it.`, "");
  if (unfinished.length) {
    lines.push("## Other unfinished items", "");
    for (const i of unfinished) lines.push(`- ${label(i.stepId)}${i.message}`);
    lines.push("");
  }
  return lines.join("\n");
}

// ------------------------------------------------------------------------------------------------ the stubs

/** A value of the declared type, as Python source: what the stub prints until it is written. */
function dummy(type: string): string {
  switch (type) {
    case "string": return '""';
    case "integer": return "0";
    case "float": return "0.0";
    case "boolean": return "False";
    case "object": return "{}";
    case "list[*]": return "[]";
    default: return "None";
  }
}

const docText = (s: string) => s.replace(/\\/g, "\\\\").replace(/"""/g, '\\"\\"\\"');
const shape = (items: IOItem[]) => `{${items.filter((i) => i.name).map((i) => `${JSON.stringify(i.name)}: ${i.type}`).join(", ")}}`;

function pythonStub(draft: Draft, s: Step, next: Step | undefined): string {
  const outputs = (s.outputs ?? []).filter((o) => o.name);
  const assets = (s.assets ?? []).map(stem);
  const expects = next && next.kind !== "router" ? next.inputs : [];
  const body = outputs.length
    ? `{\n${outputs.map((o) => `    ${JSON.stringify(o.name)}: ${dummy(o.type)},`).join("\n")}\n}`
    : "{}";
  return [
    `# ${PLACEHOLDER_MARKER}: Studio wrote this stub. Replace it with the step's script, and this line with it.`,
    `"""${docText(s.name || s.id)}: ${docText(s.description || "TODO: say what this step does.")}`,
    "",
    `Execution step of the \`${docText(draft.name || "untitled-skill")}\` procedure.`,
    "",
    `stdin:  {"state": ${docText(shape(s.inputs))}, "assets": {${assets.map((a) => `${JSON.stringify(docText(a))}: str`).join(", ")}}, "expects": ${docText(shape(expects))}}`,
    `stdout: ${docText(shape(outputs))}, one JSON object holding exactly these keys`,
    `"""`,
    "import json",
    "import sys",
    "",
    "payload = json.load(sys.stdin)",
    'state = payload["state"]',
    'assets = payload["assets"]',
    "",
    "# TODO: compute the outputs from the state and the assets. Each value below is a dummy of the declared type.",
    `json.dump(${body}, sys.stdout)`,
    "",
  ].join("\n");
}

/** The template is rendered with Python's `str.format` rules: a brace in prose is doubled. */
const prose = (s: string) => s.replace(/\{/g, "{{").replace(/\}/g, "}}");

function templateStub(s: Step): string {
  const inputs = s.inputs.filter((i) => i.name);
  const outputs = (s.outputs ?? []).filter((o) => o.name);
  const lines = [
    `<!-- ${PLACEHOLDER_MARKER}: Studio wrote this template. Replace it with the task, and this line with it. -->`,
    `# TODO: ${prose(s.name || s.id)}`,
    "",
    prose(s.description || "TODO: say what the task is."),
    "",
  ];
  if (inputs.length) {
    lines.push("Inputs:", "");
    for (const i of inputs) lines.push(IDENTIFIER.test(i.name) ? `- ${i.name}: {${i.name}}` : `- ${prose(i.name)}: (not a valid template key)`);
    lines.push("");
  }
  const assets = (s.assets ?? []).map(stem).filter((a) => IDENTIFIER.test(a));
  if (assets.length) {
    lines.push("Assets:", "");
    for (const a of assets) lines.push(`${a}:`, `{assets[${a}]}`, "");
  }
  lines.push("Answer with one JSON object holding:", "");
  for (const o of outputs) lines.push(`- \`${prose(o.name)}\` (${o.type})${o.description ? `: ${prose(o.description)}` : ""}`);
  if (!outputs.length) lines.push("- TODO: declare the step's outputs");
  lines.push("");
  return lines.join("\n");
}

function referenceStub(path: string, description: string): string {
  return [
    `<!-- ${PLACEHOLDER_MARKER}: Studio wrote this reference. Replace it, and this line with it. -->`,
    `# TODO: ${stem(path)}`,
    "",
    description ? `Load when: ${description}` : "",
    "",
    "TODO: write this reference.",
    "",
  ].join("\n");
}

/** An asset's placeholder in a form its type allows: a comment where the format has one, a JSON object holding
 *  the marker, and an empty file for anything the marker cannot sit in. */
function assetStub(path: string): string {
  const note = `${PLACEHOLDER_MARKER}: Studio wrote this asset. Replace it, and this line with it.`;
  switch (ext(path)) {
    case "md": case "markdown": case "html": case "htm": case "xml": case "svg": return `<!-- ${note} -->\nTODO\n`;
    case "json": return `${JSON.stringify({ [PLACEHOLDER_MARKER]: "TODO: replace this file" }, null, 2)}\n`;
    case "yaml": case "yml": case "toml": case "py": case "sh": case "cfg": case "ini": return `# ${note}\n# TODO\n`;
    case "txt": case "csv": case "": return `${note}\nTODO\n`;
    default: return "";
  }
}
